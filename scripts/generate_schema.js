const fs = require('fs');
const path = require('path');
const { getDb, initializeDatabase } = require('../db/database');

initializeDatabase();
const db = getDb();
const statements = db.prepare('SELECT * FROM problem_statements ORDER BY ps_number ASC').all();
console.log('Fetched statements from DB:', statements.length);

let sql = `-- ========================================================
-- SYNAPSE Hackathon - Supabase PostgreSQL Schema & Storage
-- V.S.B. Engineering College, Karur
-- Department of AI & Data Science
-- ========================================================

-- Enable UUID extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. Admins Table
CREATE TABLE IF NOT EXISTS admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    name TEXT DEFAULT 'Admin',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Problem Statements Table
CREATE TABLE IF NOT EXISTS problem_statements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ps_number INT,
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    problem_faced TEXT,
    suggested_solution TEXT,
    category TEXT NOT NULL,
    difficulty TEXT DEFAULT 'medium' CHECK(difficulty IN ('easy', 'medium', 'hard')),
    is_active INT DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Teams Table
CREATE TABLE IF NOT EXISTS teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_code TEXT UNIQUE,
    team_name TEXT NOT NULL,
    team_lead_email TEXT NOT NULL,
    team_size INT NOT NULL CHECK(team_size >= 2 AND team_size <= 4),
    password TEXT DEFAULT 'Syanp2K26',
    problem_statement_id BIGINT REFERENCES problem_statements(id),
    status TEXT DEFAULT 'registered' CHECK(status IN ('registered', 'approved', 'rejected', 'checked_in')),
    registered_at TIMESTAMPTZ DEFAULT NOW(),
    checked_in_at TIMESTAMPTZ,
    project_repo TEXT,
    project_demo TEXT,
    submission_notes TEXT,
    submission_file_url TEXT
);

-- 4. Team Members Table
CREATE TABLE IF NOT EXISTS team_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT NOT NULL,
    year TEXT NOT NULL,
    department TEXT NOT NULL,
    college TEXT NOT NULL,
    is_leader INT DEFAULT 0
);

-- 5. Announcements Table
CREATE TABLE IF NOT EXISTS announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    priority TEXT DEFAULT 'normal' CHECK(priority IN ('low', 'normal', 'high', 'urgent')),
    is_active INT DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Schedule Table
CREATE TABLE IF NOT EXISTS schedule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT,
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ,
    location TEXT,
    event_type TEXT DEFAULT 'general' CHECK(event_type IN ('general', 'workshop', 'break', 'judging', 'ceremony')),
    is_active INT DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Event Settings Table
CREATE TABLE IF NOT EXISTS event_settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

-- ========================================================
-- Supabase Storage Setup (hackathon-files bucket)
-- ========================================================
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('hackathon-files', 'hackathon-files', true, 52428800, NULL)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Storage RLS Policies
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE policyname = 'Public Access for Hackathon Files'
    ) THEN
        CREATE POLICY "Public Access for Hackathon Files"
        ON storage.objects FOR SELECT
        USING (bucket_id = 'hackathon-files');
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE policyname = 'Public Upload for Hackathon Submissions'
    ) THEN
        CREATE POLICY "Public Upload for Hackathon Submissions"
        ON storage.objects FOR INSERT
        WITH CHECK (bucket_id = 'hackathon-files');
    END IF;
END $$;

-- ========================================================
-- Row Level Security (RLS) Policies
-- ========================================================
ALTER TABLE problem_statements ENABLE ROW LEVEL SECURITY;
ALTER TABLE teams ENABLE ROW LEVEL SECURITY;
ALTER TABLE team_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE announcements ENABLE ROW LEVEL SECURITY;
ALTER TABLE schedule ENABLE ROW LEVEL SECURITY;
ALTER TABLE event_settings ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public read problem_statements') THEN
        CREATE POLICY "Public read problem_statements" ON problem_statements FOR SELECT USING (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public read announcements') THEN
        CREATE POLICY "Public read announcements" ON announcements FOR SELECT USING (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public read schedule') THEN
        CREATE POLICY "Public read schedule" ON schedule FOR SELECT USING (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public read event_settings') THEN
        CREATE POLICY "Public read event_settings" ON event_settings FOR SELECT USING (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public insert teams') THEN
        CREATE POLICY "Public insert teams" ON teams FOR INSERT WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public read teams') THEN
        CREATE POLICY "Public read teams" ON teams FOR SELECT USING (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public update teams') THEN
        CREATE POLICY "Public update teams" ON teams FOR UPDATE USING (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public insert team_members') THEN
        CREATE POLICY "Public insert team_members" ON team_members FOR INSERT WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Public read team_members') THEN
        CREATE POLICY "Public read team_members" ON team_members FOR SELECT USING (true);
    END IF;
END $$;

-- ========================================================
-- Default Settings Seed
-- ========================================================
INSERT INTO event_settings (key, value) VALUES
    ('event_name', 'SYNAPSE - 24-Hour Hackathon'),
    ('event_date', 'November 15-16, 2026'),
    ('registration_open', '1'),
    ('max_teams', '50'),
    ('contact_email', 'synapse@vsb.edu.in'),
    ('contact_phone', '+91 98765 43210')
ON CONFLICT (key) DO NOTHING;

-- Seed Problem Statements
`;

function esc(str) {
    if (!str) return "''";
    return "'" + str.replace(/'/g, "''") + "'";
}

statements.forEach(s => {
    sql += `INSERT INTO problem_statements (ps_number, title, description, problem_faced, suggested_solution, category, difficulty)
VALUES (${s.ps_number}, ${esc(s.title)}, ${esc(s.description)}, ${esc(s.problem_faced)}, ${esc(s.suggested_solution)}, ${esc(s.category)}, ${esc(s.difficulty)})
ON CONFLICT DO NOTHING;\n`;
});

const outPath = path.join(__dirname, '..', 'supabase_schema.sql');
fs.writeFileSync(outPath, sql, 'utf8');
console.log('Successfully wrote supabase_schema.sql at:', outPath, 'Bytes:', fs.statSync(outPath).size);
